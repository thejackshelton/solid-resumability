/**
 * The demo's whole side of `unplugin-solid-resumability`.
 *
 * Everything that used to be a script in this directory — the comptime pass and
 * its expect-provable gate, the source-to-source substitution, the deferral
 * group's glue module, the two HTML rewrites, the captured first paint — is now
 * the plugin's, and this file is what is left of the demo's half: a
 * declaration. It says which components to prove, which pages carry them, and
 * the five facts about *this* application that no analysis can reach (the entry
 * modules to swap, the root element, the glue the mount points call, the
 * substring the first paint has to contain, and where the fixtures page writes
 * its fallback branch). Everything else the pass derives — including whether
 * that branch may go.
 *
 * One declaration, three callers: `build/config.mjs` (the four production
 * builds and the dev server), `scripts/emit-artifacts.mjs` (`pnpm emit`, which
 * runs the same three stage bodies with no bundler around them), and
 * `build/substitute.mjs` (the fidelity test's handle on the rewrite).
 *
 * ── Why the plugin is consumed node-side only ─────────────────────────────
 * `runtime` names the specifier generated modules would import the browser half
 * through, and the demo points it back at the repository's own `src/resume/**`
 * rather than at `unplugin-solid-resumability/runtime`. That is not a
 * workaround: pnpm materializes an installed dependency under `node_modules`,
 * and `scripts/check-zero-eager.mjs` scores every module id containing
 * `/node_modules/` as a dependency and fails the build for any that is not on
 * the frozen framework list. The demo links the plugin with `link:` (a real
 * symlink, so its realpath is outside `node_modules`) and consumes it in the
 * build process only; what reaches the browser is the same relative import the
 * eager chunk has always carried, so the module graph the gates know is the
 * module graph they still see.
 */

import { ARTIFACT_ROOT, DEMO_ROOT, FIXTURES, REPO_ROOT, RESUMED, RULE } from "./fixtures.mjs";

/** The corpus module the todos page resumes a component out of. */
const APP_MOUNT = RESUMED[0];

/**
 * The rewritten module's opening prose.
 *
 * Anchored, not frozen: `plugin/test/substitute.test.ts` pins the emitted
 * module to a sha256, and a banner is the one part of that module nothing can
 * derive — so a reworded banner moves the hash and the two have to move
 * together, in one change, or the plugin's proof that the AST substituter *is*
 * the string rewrite it replaced goes red against a difference that is not a
 * difference in the rewrite.
 *
 * It moved once, here, for cause. Two citations in it had gone stale: the
 * generator (the rewrite is `unplugin-solid-resumability`'s substitution stage
 * now, not the demo script that used to do it by hand), and the coverage
 * fraction — `app 1/5` was the verdict when the pass proved one component of
 * this module and is `app 3/5` today. The sentence built on that fraction was
 * false in a way the fraction alone does not show, which is the reason the
 * rewording is not a cosmetic one: the pass proves three components of this
 * module, and exactly ONE of them is resumed on the wire.
 */
export const SUBSTITUTION_BANNER = `// Generated by unplugin-solid-resumability from app/src/app.tsx. Do not edit.
//
// The corpus module with ONE edit a resumability compiler would make: the
// mount point of \`Header\` — the single component this demo RESUMES — no
// longer renders a component. It publishes the live store and claims the
// element already carrying the resumed component, and \`Header\`'s body is not
// in this file at all. The other four components are the corpus's own source,
// unchanged.
//
// The pass's verdict for this module is app 3/5 (docs/coverage/coverage.json),
// and the other two proved components are NOT substituted out. What flips a
// \`MainSection\` or \`Footer\` guard is a store write, and a store write is the
// deferred group's — so their bodies stay where the group renders them the
// ordinary way, and a mount here would ship empty. Three verdicts, one
// resumption: read the fraction as coverage, never as components resumed.
`;

/** The demo's two HTML entries, and the module each one swaps to when resumable. */
const ENTRIES = {
  fixtures: { from: "/src/pages/fixtures-classic.ts", to: "/src/pages/fixtures-resumable.ts" },
  todos: { from: "/src/pages/todos.ts", to: "/src/pages/todos-resumable.ts" },
  rule: { from: "/src/pages/rule-classic.ts", to: "/src/pages/rule-resumable.ts" },
};

/**
 * The options, for a build that captures the first paint of `capture` and of
 * nothing else.
 *
 * The parameter exists because this demo builds one page per build (see the
 * long note in `config.mjs`): capturing a page means running the built chunk of
 * its group, and only the build that produced that chunk has one. A build of
 * the fixtures page declares the todos page all the same — its mounts still
 * have to be proven, or the pass would prune artifacts the other build needs —
 * but declares it with no capture.
 *
 * @param {{ capture?: string[] }} [options]
 * @returns {import("unplugin-solid-resumability/types").ResumabilityOptions}
 */
export function demoResumability({ capture = ["fixtures", "todos", "rule"] } = {}) {
  const captures = new Set(capture);

  return {
    // The plugin's root is the demo, which is also vite's: the build manifest
    // names the group module the way this root sees it, and the capture looks
    // it up under that same name.
    root: DEMO_ROOT,
    // Module paths in the artifacts are relative to the repository, because the
    // corpus they describe lives in `app/` and the artifacts have said so since
    // the first emission. `demo/artifacts/**` is a checked reference tree; this
    // is the line that keeps it byte-stable.
    corpusRoot: REPO_ROOT,
    artifactDir: ARTIFACT_ROOT,
    generatedDir: "src/generated",

    // Declared, and pointed at the repository's own runtime rather than at the
    // package's — see the note at the top of this file.
    runtime: "../../src/resume",

    /**
     * One policy off its default, and it is a per-PAGE effect stated once.
     *
     * `auto-omit` drops the fallback branch of every page that declares one and
     * is fully provable. Exactly one page here qualifies. The fixtures page's
     * five mounts all come back provable, so it can never take the branch and
     * the build emits no chunk for it. The todos page declares no branch at
     * all — `App` is unprovable and always will be (its mount point IS the
     * provider call), so its four bodies and the framework they need are the
     * deferred GROUP: two the pass cannot prove, two it proves but may not
     * substitute — what flips a `MainSection` or `Footer` guard is a store
     * write, the store is the group's, and a substituted mount would ship
     * empty. The group is a different mechanism with a different job: it is
     * fetched on the first interaction, deliberately, and nothing here may
     * take it away.
     */
    policies: { fallback: "auto-omit" },

    mounts: [
      ...FIXTURES.map((fixture) => ({
        component: fixture.component,
        source: fixture.source,
        artifact: fixture.artifact,
        page: fixture.page,
      })),
      ...RULE.map((fixture) => ({
        component: fixture.component,
        source: fixture.source,
        artifact: fixture.artifact,
        page: fixture.page,
      })),
      {
        component: APP_MOUNT.component,
        source: APP_MOUNT.source,
        artifact: APP_MOUNT.artifact,
        page: APP_MOUNT.page,
        // The todos page ships the corpus module with this one component's
        // mount point resumed and its body gone. Where the rewrite lands and
        // what glue claims it are the demo's to say; the removal span, the
        // mount expression and the re-rooted imports are the stage's to derive.
        substitute: {
          out: "app.resumable.tsx",
          claim: { module: "src/todos-resume.ts" },
          banner: SUBSTITUTION_BANNER,
        },
      },
    ],

    pages: [
      {
        id: "fixtures",
        html: "fixtures.html",
        entry: ENTRIES.fixtures,
        // The reason the resumable fixtures build ships no `template.js`: the
        // bytes are in the document, where the browser needs no JavaScript to
        // use them.
        //
        // One flag, two obligations, and which one a mount gets is the pass's
        // to decide rather than this file's. Four of the five mounts declared
        // above are EMPTY in `fixtures.html` and the pass fills them with the
        // emitted template. The fifth — `KeyedRoster.RosterList` — declares a
        // keyed region, so its template is an empty container and the document
        // carries the items; the pass gives it the VERIFYING edit instead, and
        // a build whose page drifted from the template, lost a key or repeated
        // one fails here rather than serving a page the resumer will misread.
        // Written or carried, one edit per mount, never neither.
        inlineTemplates: true,

        // Where this page's fallback branch is written, which is the only part
        // of the omission the plugin cannot derive. WHETHER to omit is the
        // pass's call — every mount declared above is provable, so nothing on
        // this page can reach the ordinary renderer — and under
        // `policies.fallback: 'auto-omit'` the branch's `import()` is rewritten
        // out before the bundler resolves it. No chunk is emitted for
        // `src/fallback.ts` at all: not a smaller one, not a stub, none. The
        // long note at the top of `src/fallback.ts` is where the derivation was
        // written down before anything implemented it.
        fallback: { module: "src/resumable-page.ts", specifier: "./fallback.ts" },
      },
      {
        id: "todos",
        html: "todos.html",
        entry: ENTRIES.todos,
        // No inlining here, and no empty `#root` either — the todos page's
        // markup is a first paint captured from the built group chunk, which is
        // what `prerender` below does once that chunk exists.
        group: {
          moduleId: "src/todos-group.ts",
          entryComponent: "App",
          carryFocus: true,
          rootSelector: "#root",
          glue: {
            module: "src/todos-resume.ts",
            createMount: "createMount",
            offerClaim: "offerClaim",
          },
          render: { module: "@solidjs/web", named: "render" },
        },
        prerender: captures.has("todos")
          ? {
              rootSelector: "#root",
              // The app's loading paragraph. `MainSection` and `Footer` render
              // behind a `Show` inside `Loading`, and the projection that fills
              // the store is asynchronous — a snapshot taken before control
              // returns to the event loop cannot have resolved it. A capture
              // without this substring in it caught a state that is not the
              // first paint.
              expectMarkup: ['class="loading"'],
              execute: "execute",
            }
          : false,
      },
      {
        id: "rule",
        html: "rule.html",
        entry: ENTRIES.rule,
        inlineTemplates: true,
        prerender: false,
      },
    ],
  };
}
